import { readFile } from 'node:fs/promises';
import path from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outputPath = path.join(root, 'public', 'sw.js');
const checkOnly = process.argv.includes('--check');
const banner = '// Generated by npm run build:service-worker. Do not edit directly.';

const result = await build({
    absWorkingDir: root,
    entryPoints: ['service-worker/sw.ts'],
    bundle: true,
    format: 'iife',
    legalComments: 'none',
    logLevel: 'silent',
    outfile: outputPath,
    platform: 'browser',
    target: ['es2022'],
    write: !checkOnly,
    banner: { js: banner },
});

if (checkOnly) {
    const generated = result.outputFiles?.[0]?.text;
    if (!generated) throw new Error('The service-worker build produced no output.');

    let committed;
    try {
        committed = await readFile(outputPath, 'utf8');
    } catch {
        throw new Error('public/sw.js is missing. Run npm run build:service-worker.');
    }

    if (committed !== generated) {
        throw new Error('public/sw.js is stale. Run npm run build:service-worker and commit it.');
    }
}
